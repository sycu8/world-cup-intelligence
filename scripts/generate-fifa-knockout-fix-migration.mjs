/**
 * Generates migrations to fix WC 2026 knockout pairings vs FIFA Match Centre.
 * Run: node scripts/generate-fifa-knockout-fix-migration.mjs
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { GROUPS } from './fifa-wc2026-official-data.mjs';
import { NATION_ISO } from './nationIsoCodes.mjs';
import { allFifaKickoffs, FIFA_KICKOFF_SOURCE } from './wc2026-fifa-kickoffs.mjs';
import { FIFA_R32_MATCH_SLOTS } from './fifa-r32-bracket.mjs';
import { KNOCKOUT_MATCHES } from './fifa-wc2026-official-data.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

function sqlStr(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

/** @param {string} short FIFA IdCountry code (e.g. RSA, CAN) */
function fifaShortToTeamId(short) {
  const nation = Object.entries(NATION_ISO).find(([, m]) => m.short === short)?.[0];
  if (!nation) throw new Error(`Unknown FIFA country code: ${short}`);
  for (const [group, teams] of Object.entries(GROUPS)) {
    const slot = teams.indexOf(nation) + 1;
    if (slot > 0) return `team-w26-${group.toLowerCase()}${slot}`;
  }
  throw new Error(`Nation ${nation} not in WC2026 groups`);
}

const byFifaNumber = new Map(allFifaKickoffs().map((r) => [r.fifaNumber, r]));
const r32FifaNumbers = new Set(FIFA_R32_MATCH_SLOTS.map((s) => s.fifaNumber));

const teamUpdates = [...r32FifaNumbers]
  .sort((a, b) => a - b)
  .map((fifaNumber) => {
    const row = byFifaNumber.get(fifaNumber);
    if (!row?.home || !row?.away) {
      throw new Error(`Missing teams for FIFA R32 #${fifaNumber}`);
    }
    const internal = KNOCKOUT_MATCHES.find((m) => m.fifaNumber === fifaNumber);
    if (!internal) throw new Error(`No internal R32 match for FIFA #${fifaNumber}`);

    const homeTeamId = fifaShortToTeamId(row.home);
    const awayTeamId = fifaShortToTeamId(row.away);
    const parts = [
      `-- FIFA #${fifaNumber} ${row.home} vs ${row.away}`,
      'UPDATE matches SET',
      `  home_team_id = ${sqlStr(homeTeamId)},`,
      `  away_team_id = ${sqlStr(awayTeamId)},`,
      `  fifa_match_id = ${sqlStr(row.fifaMatchId)},`,
    ];

    if (row.completed) {
      parts.push(
        `  status = 'completed',`,
        `  minute = 90,`,
        `  home_score = ${row.homeScore ?? 0},`,
        `  away_score = ${row.awayScore ?? 0},`,
      );
    }

    parts.push(`  updated_at = datetime('now')`, `WHERE id = ${sqlStr(internal.matchId)};`);
    return parts.join('\n');
  })
  .join('\n\n');

const mig35 = `-- Fix WC 2026 knockout team pairings from FIFA Match Centre
-- Source: ${FIFA_KICKOFF_SOURCE}
-- Generated by scripts/generate-fifa-knockout-fix-migration.mjs on ${new Date().toISOString()}
-- Replaces wrong A1-vs-B2 simplified bracket with official FIFA R32 pairings

${teamUpdates}
`;

const bracketDeletes = `DELETE FROM match_bracket_links
WHERE tournament_id = 't-2026'
  AND rule_type = 'group_rank'
  AND target_match_id LIKE 'm-w26-r32-%';`;

const bracketInserts = FIFA_R32_MATCH_SLOTS.flatMap((slot) => {
  const rows = [];
  for (const [side, rule] of [
    ['home', slot.home],
    ['away', slot.away],
  ]) {
    if (rule.kind !== 'group_rank') continue;
    const id = `bl-fifa-${slot.matchId.replace('m-w26-', '')}-${side[0]}`;
    const ruleJson = JSON.stringify({ group: rule.group, rank: rule.rank });
    rows.push(
      `  (${sqlStr(id)}, 't-2026', NULL, ${sqlStr(slot.matchId)}, ${sqlStr(side)}, 'group_rank', ${sqlStr(ruleJson)})`,
    );
  }
  return rows;
}).join(',\n');

const mig36 = `-- Replace simplified R32 group_rank bracket links with FIFA official pairings
-- Third-place slots (1X vs 3Y) are filled by applyBestThirdQualifiers, not bracket links
-- Generated by scripts/generate-fifa-knockout-fix-migration.mjs on ${new Date().toISOString()}

${bracketDeletes}

INSERT INTO match_bracket_links (id, tournament_id, source_match_id, target_match_id, target_slot, rule_type, rule_json) VALUES
${bracketInserts};
`;

writeFileSync(path.join(__dirname, '..', 'migrations', '0035_fifa_knockout_pairings.sql'), mig35, 'utf8');
writeFileSync(path.join(__dirname, '..', 'migrations', '0036_fifa_r32_bracket_links.sql'), mig36, 'utf8');
console.log('Wrote migrations/0035_fifa_knockout_pairings.sql');
console.log('Wrote migrations/0036_fifa_r32_bracket_links.sql');
