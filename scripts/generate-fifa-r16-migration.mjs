/**
 * Generates migration for Round of 16 teams (and R32 13–16 repair) from FIFA Match Centre.
 * Run: node scripts/fetch-fifa-wc2026-calendar.mjs && node scripts/generate-fifa-r16-migration.mjs
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { GROUPS } from './fifa-wc2026-official-data.mjs';
import { KNOCKOUT_MATCHES } from './fifa-wc2026-official-data.mjs';
import { NATION_ISO } from './nationIsoCodes.mjs';
import { allFifaKickoffs, FIFA_KICKOFF_SOURCE } from './wc2026-fifa-kickoffs.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

function sqlStr(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

/** @param {string} short FIFA IdCountry code (e.g. RSA, CAN) */
function fifaShortToTeamId(short) {
  const nation = Object.entries(NATION_ISO).find(([, m]) => m.short === short)?.[0];
  if (!nation) throw new Error(`Unknown FIFA country code: ${short}`);
  for (const [group, teams] of Object.entries(GROUPS)) {
    const slot = teams.indexOf(nation) + 1;
    if (slot > 0) return `team-w26-${group.toLowerCase()}${slot}`;
  }
  throw new Error(`Nation ${nation} not in WC2026 groups`);
}

const byFifaNumber = new Map(allFifaKickoffs().map((r) => [r.fifaNumber, r]));
const byMatchId = new Map(KNOCKOUT_MATCHES.map((m) => [m.matchId, m]));

/** R32 matches 13–16 were wrong in production before 0035; refresh teams + scores. */
const R32_REPAIR = ['m-w26-r32-13', 'm-w26-r32-14', 'm-w26-r32-15', 'm-w26-r32-16'];
const R16_MATCH_IDS = KNOCKOUT_MATCHES.filter((m) => m.matchId.includes('-r16-')).map((m) => m.matchId);

function buildUpdate(matchId, row, { includeScores }) {
  if (!row?.home || !row?.away) {
    throw new Error(`Missing teams for FIFA #${row?.fifaNumber} (${matchId})`);
  }
  const homeTeamId = fifaShortToTeamId(row.home);
  const awayTeamId = fifaShortToTeamId(row.away);
  const parts = [
    `-- FIFA #${row.fifaNumber} ${row.home} vs ${row.away}`,
    'UPDATE matches SET',
    `  home_team_id = ${sqlStr(homeTeamId)},`,
    `  away_team_id = ${sqlStr(awayTeamId)},`,
    `  fifa_match_id = ${sqlStr(row.fifaMatchId)},`,
  ];

  if (includeScores && row.completed) {
    parts.push(
      `  status = 'completed',`,
      `  minute = 90,`,
      `  home_score = ${row.homeScore ?? 0},`,
      `  away_score = ${row.awayScore ?? 0},`,
    );
  } else if (includeScores && !row.completed) {
    parts.push(`  status = 'scheduled',`, `  minute = 0,`, `  home_score = 0,`, `  away_score = 0,`);
  }

  parts.push(`  updated_at = datetime('now')`, `WHERE id = ${sqlStr(matchId)};`);
  return parts.join('\n');
}

const blocks = [];

for (const matchId of R32_REPAIR) {
  const internal = byMatchId.get(matchId);
  if (!internal) throw new Error(`No internal match ${matchId}`);
  const row = byFifaNumber.get(internal.fifaNumber);
  blocks.push(buildUpdate(matchId, row, { includeScores: true }));
}

for (const matchId of R16_MATCH_IDS) {
  const internal = byMatchId.get(matchId);
  if (!internal) throw new Error(`No internal match ${matchId}`);
  const row = byFifaNumber.get(internal.fifaNumber);
  blocks.push(buildUpdate(matchId, row, { includeScores: true }));
}

const sql = `-- Round of 16 teams from FIFA Match Centre (+ repair R32 13–16)
-- Source: ${FIFA_KICKOFF_SOURCE}
-- Generated by scripts/generate-fifa-r16-migration.mjs on ${new Date().toISOString()}

${blocks.join('\n\n')}
`;

const outPath = path.join(__dirname, '..', 'migrations', '0037_fifa_r16_teams.sql');
writeFileSync(outPath, sql, 'utf8');
console.log(`Wrote ${outPath} (${blocks.length} updates)`);
